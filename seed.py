def seed_if_empty(db):
    """تضيف البيانات الأولية فقط إذا الجداول فاضية."""
    if db.query(Variety).count() == 0:
        for ar, en, cal, sug, per, desc in VARIETIES:
            db.add(Variety(name_ar=ar, name_en=en, calories_per_100g=cal,
                           sugar_per_100g=sug, calories_per_date=per, description=desc))
    if db.query(Company).count() == 0:
        for (name, en, desc, country, city, year, varieties,
             site, phone, rating, featured) in COMPANIES:
            db.add(Company(name=name, name_en=en, description=desc, country=country,
                           city=city, founded_year=year, varieties=varieties,
                           website=site, phone=phone, rating=rating, featured=featured))
    db.commit()
